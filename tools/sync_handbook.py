#!/usr/bin/env python3
"""Copy the organization-wide Handbook (policies, procedures, guides) from the Joint-Operations repository
into docs/handbook/ and write docs/handbook.json for the Documentation page.

The Joint-Operations repository stays the source. Do not edit the copies here; change them there, then re-run:
    python3 tools/sync_handbook.py ../Joint-Operations
Guides about the mod itself (player guide, Linux, sessions, its website) stay in the Joint Operations documentation.
"""
import json, pathlib, re, shutil, sys

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else HERE.parent / "joint-operations").resolve()
MOD_ONLY = {"HP-GDE-001", "HP-GDE-002", "HP-GDE-007", "HP-GDE-012", "HP-GDE-015", "HP-GDE-016", "HP-GDE-020"}
ORIGIN = "https://github.com/Hound-Protocol/Joint-Operations/blob/main/"
GROUP = {"Policy": "policies", "Procedure": "procedures", "Guide": "guides"}

guides = json.loads((SRC / "data/guides.json").read_text(encoding="utf-8"))["guides"]
out_dir = HERE / "docs/handbook"
shutil.rmtree(out_dir, ignore_errors=True); out_dir.mkdir(parents=True)
items = []
for g in guides:
    if g["code"] in MOD_ONLY: continue
    src = SRC / g["path"]
    name = src.name
    shutil.copyfile(src, out_dir / name)
    items.append({
        "id": g["id"], "code": g["code"], "title": g["title"], "group": GROUP[g["type"]], "type": g["type"],
        "audience": g["audience"], "owner": g["owner"], "version": g["version"], "effective": g["effective"],
        "summary": g["summary"], "path": f"docs/handbook/{name}", "origin": ORIGIN + g["path"],
    })
order = {"Policy": 0, "Procedure": 1, "Guide": 2}
items.sort(key=lambda d: (order[d["type"]], d["code"]))
(HERE / "docs/handbook.json").write_text(json.dumps({
    "note": "Generated by tools/sync_handbook.py from the Joint-Operations repository. Do not edit by hand.",
    "source": "https://github.com/Hound-Protocol/Joint-Operations/tree/main/docs/guides",
    "docs": items}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"synced {len(items)} handbook documents ({len(guides) - len(items)} stay with the mod)")
