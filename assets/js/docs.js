  var lastZone = null;
  function route() {
    var hash = decodeURIComponent(location.hash.replace(/^#\/?/, "")), id = hash.split(":")[0], anchor = hash.indexOf(":") > 0 ? hash : "";
    if (!id) { lastZone = null; return viewPick(); }
    var d = byId(id), z = d ? d.zone : (id === "library" || id === "handbook" ? id : null);
    if (!z) { lastZone = null; return viewPick(); }
    if (!d) d = zoneDocs(z)[0];
    document.title = d.title + " · Hound Protocol";
    if (lastZone !== z) { state.zone = z; state.q = ""; state.aud = "All"; viewZone(z, d); lastZone = z; }
    Array.prototype.forEach.call(APP.querySelectorAll(".card"), function (c) {
      var on = c.getAttribute("data-id") === d.id; c.classList.toggle("on", on); if (on) c.setAttribute("aria-current", "page"); else c.removeAttribute("aria-current");
      if (on && !c.closest(".drawer").classList.contains("open")) setDrawer(c.closest(".drawer"), true);
    });
    var shown = document.querySelector(".sheet .doc") && current && current.id === d.id && anchor;
    var target = shown && document.getElementById(anchor);
    if (target) { target.scrollIntoView(); return; }
    showSheet(d, anchor);
  }

  /* ---------- Keyboard: Ctrl K or / searches; arrows move between files; Esc clears ---------- */
  document.addEventListener("keydown", function (e) {
    var q = document.getElementById("q"), t = e.target, typing = t && (t.tagName === "INPUT" || t.tagName === "TEXTAREA");
    if (q && ((e.key === "k" && (e.ctrlKey || e.metaKey)) || (e.key === "/" && !typing))) { e.preventDefault(); q.focus(); q.select(); return; }
    if (q && e.key === "Escape" && (t === q || state.q)) { if (state.q) { q.value = ""; state.q = ""; applyFilter(true); } q.blur(); return; }
    if (!q || (e.key !== "ArrowDown" && e.key !== "ArrowUp" && e.key !== "ArrowLeft" && e.key !== "ArrowRight")) return;
    if (t !== q && !(t && t.classList && t.classList.contains("card"))) return;
    var cards = Array.prototype.filter.call(APP.querySelectorAll(".card"), function (c) { return !c.hidden && c.closest(".drawer").classList.contains("open") && !c.closest(".drawer").hidden; });
    if (!cards.length) return;
    var i = cards.indexOf(document.activeElement); e.preventDefault();
    if (i < 0) { cards[0].focus(); return; }
    var step = (e.key === "ArrowDown" || e.key === "ArrowRight") ? 1 : -1;
    var next = cards[Math.max(0, Math.min(cards.length - 1, i + step))]; if (next) next.focus();
  });
