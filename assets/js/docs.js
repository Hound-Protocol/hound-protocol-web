  /* Hide files that do not match; open the drawers that still have files; best first is the file order */
  var filterSeq = 0;
  function applyFilter(fromTyping) {
    var z = state.zone, ws = words(state.q), seq = ++filterSeq;
    var run = function () {
      if (seq !== filterSeq) return;
      var shown = 0, total = 0;
      Array.prototype.forEach.call(APP.querySelectorAll(".drawer"), function (dr) {
        var n = 0, c = 0;
        Array.prototype.forEach.call(dr.querySelectorAll(".card"), function (card) {
          var d = byId(card.getAttribute("data-id")); total++; c++;
          var ok = matches(d, ws) && (state.aud === "All" || z !== "handbook" || d.audience === state.aud);
          card.hidden = !ok; if (ok) { n++; shown++; }
        });
        dr.hidden = n === 0 && (ws.length > 0 || state.aud !== "All");
        var label = dr.querySelector("[data-n]"); label.textContent = (ws.length || state.aud !== "All") ? n + " of " + c : c + " files";
        if (ws.length || state.aud !== "All") setDrawer(dr, n > 0);
        else if (fromTyping) setDrawer(dr, dr.querySelector(".card.on") != null);
      });
      var count = document.getElementById("count");
      if (count) count.textContent = (ws.length || state.aud !== "All") ? (shown ? shown + " of " + total + " files match" : "No file matches. Try fewer words, or search by Content.") : "";
    };
    if (state.mode === "content" && ws.length) {
      Promise.all(zoneDocs(z).map(text)).then(run, run);
    } else run();
  }

