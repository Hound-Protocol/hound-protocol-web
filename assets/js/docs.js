  /* ---------- Search: every word must match ---------- */
  function words(q) { return q.toLowerCase().split(/[^\wÀ-ɏ]+/).filter(Boolean); }
  function nameHay(d) { return (d.num + " " + d.title + " " + (d.summary || "") + " " + (d.audience || "") + " " + (d.owner || "") + " " + d.kind).toLowerCase(); }
  function matches(d, ws) {
    if (!ws.length) return true;
    var hay = state.mode === "content" ? (nameHay(d) + " " + (texts[d.id] || "")).toLowerCase() : nameHay(d);
    return ws.every(function (w) { return hay.indexOf(w) >= 0; });
  }

