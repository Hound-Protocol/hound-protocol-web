  /* Mark the first match of the search words in the opened page */
  function highlight(el) {
    var ws = words(state.q); if (!ws.length || state.mode !== "content" || !el) return null;
    var first = null, re = new RegExp("(" + ws.map(function (w) { return w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }).join("|") + ")", "ig");
    var walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, null), nodes = [], n;
    while ((n = walker.nextNode())) nodes.push(n);
    nodes.forEach(function (node) {
      if (!re.test(node.nodeValue)) return; re.lastIndex = 0;
      var span = document.createElement("span"); span.innerHTML = esc(node.nodeValue).replace(new RegExp("(" + ws.map(function (w) { return esc(w).replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }).join("|") + ")", "ig"), "<mark>$1</mark>");
      node.parentNode.replaceChild(span, node);
      if (!first) first = span.querySelector("mark");
    });
    return first;
  }

